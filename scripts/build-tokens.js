#!/usr/bin/env node
// Generates the token CSS and Tailwind preset files from designTokens.js.
const fs = require('node:fs');
const path = require('node:path');
const { validateTokens } = require('./tokens/validate');

const PLACEHOLDER = (name) => `/* ${name}: generated by scripts/build-tokens.js */\n`;

// Emitters are filled in by later tasks; each returns the file contents.
const emitters = {
  'themes/default.css': () => PLACEHOLDER('themes/default.css'),
  'themes/default-auto.css': () => PLACEHOLDER('themes/default-auto.css'),
  'themes/forest.css': () => PLACEHOLDER('themes/forest.css'),
  'themes/forest-auto.css': () => PLACEHOLDER('themes/forest-auto.css'),
  'tokens.css': () => PLACEHOLDER('tokens.css'),
  'theme.css': () => PLACEHOLDER('theme.css'),
  'typography.css': () => PLACEHOLDER('typography.css'),
  'tailwind-preset.js': () => '// tailwind-preset.js: generated by scripts/build-tokens.js\nmodule.exports = {};\n',
};

function generate(tokens) {
  validateTokens(tokens);
  const files = {};
  for (const [file, emit] of Object.entries(emitters)) files[file] = emit(tokens);
  return files;
}

function main(argv) {
  const check = argv.includes('--check');
  const outIdx = argv.indexOf('--out');
  const out = outIdx === -1 ? 'dist' : argv[outIdx + 1];
  if (!out) throw new Error('--out requires a directory');

  const files = generate(require('../designTokens.js'));

  if (check) {
    const differing = Object.keys(files).filter((f) => {
      const p = path.join(out, f);
      return !fs.existsSync(p) || fs.readFileSync(p, 'utf8') !== files[f];
    });
    differing.forEach((f) => console.log(path.join(out, f)));
    process.exit(differing.length ? 1 : 0);
  }

  for (const [f, content] of Object.entries(files)) {
    const p = path.join(out, f);
    fs.mkdirSync(path.dirname(p), { recursive: true });
    fs.writeFileSync(p, content);
  }
}

if (require.main === module) main(process.argv.slice(2));

module.exports = { generate };
